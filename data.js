// Difficulty is classified from the puzzle's actual content — and, since
// a puzzle is genuinely hard only when MOST of it is hard, this looks at
// how many of the 4 groups are advanced, not just whether any single
// group is. (Earlier versions of this file called a puzzle "black belt"
// if even one group was a leg-lock group, even when the other three were
// plain fundamentals — that made "black belt" mean almost nothing.)
//
// BLACK_BELT_TERMS: material a white or blue belt typically hasn't seen.
// PURPLE_BELT_TERMS: intermediate material — beyond fundamentals, short
