function classifyDifficulty(groups) {
  // A group counts as "advanced" if at least 3 of its 4 items are
  // black-tier terms (or advanced-tier names) — i.e. the group as a
  // whole, not just a stray word, is genuinely deep material.
  const advancedGroupCount = groups.filter(items => {
    const hits = items.filter(w => BLACK_BELT_TERMS.has(w) || ADVANCED_NAME_POOL.has(w)).length;
    return hits >= 3;
  }).length;

  // Black belt requires real breadth: at least half the puzzle (2 of its
  // 4 groups) has to be advanced-tier, not just one isolated group.
  if (advancedGroupCount >= 2) return "black";
  // Exactly one deep group, or a lighter dusting of advanced material
  // spread thinner, reads as purple — real exposure, not a full system.
  if (advancedGroupCount === 1) return "purple";

  const items = groups.flat();
  let score = 0;
  items.forEach(w => {
    if (PURPLE_BELT_TERMS.has(w)) score += 1;
    else if (WHITE_BELT_TERMS.has(w)) score -= 1;
  });
  if (score <= -2) return "white";
  if (score <= 2) return "blue";
  return "purple";
}

